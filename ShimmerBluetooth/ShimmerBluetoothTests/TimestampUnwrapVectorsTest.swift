/// The timestamp-unwrap rule, run against the vectors every Shimmer host API is
/// checked against.
///
/// The set is specified and generated in the firmware repository -
/// `log-and-stream-common`, `Test/conformance/timestamp_unwrap.json`, beside the
/// prose it encodes and a reference implementation that regenerates and
/// re-checks it in CI. The Java, C#, Python and TypeScript APIs load that file
/// directly; a classic Xcode project would need four hand-edited entries in
/// project.pbxproj to carry a resource nothing compiles, so this target gets the
/// same vectors as generated source instead:
///
///     python Test/host/crosscheck_timestamp_unwrap.py --emit swift
///
/// Why go to that trouble for what looks like arithmetic: five implementations
/// of one wire format drifted apart once already, and the same unwrap defect sat
/// in all five for years - each reviewed on its own, against prose, by people
/// who had no way to run the others. A shared set turns "these should agree"
/// into something a suite fails on.

/// One vector: a raw counter sequence and what every host must make of it.
struct UnwrapVector {
    let id: String
    let modulo: Int
    let reorderWindowTicks: Double
    let raw: [Double]
    let expectedUnwrapped: [Double]
    let expectedRejected: [Bool]
    let expectedFinalCycle: Int
}

/// One window derivation: a sampling rate and the window it must produce.
struct WindowDerivationCase {
    let samplingRateHz: Double?
    let timestampBits: Int
    let expectedReorderWindowTicks: Double
    let tolerance: Double
}

