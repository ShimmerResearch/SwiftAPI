final class TimestampUnwrapVectorsTest: XCTestCase {

    /// A bumped revision means the rule moved. Read the upstream change before
    /// touching anything here.
    func testRevisionIsTheOneThisSuiteWasWrittenAgainst() {
        XCTAssertEqual(sharedVectorRevision, 1)
        XCTAssertEqual(sharedTicksPerSecond, Int(TimestampUnwrap.rtcTicksPerSecond))
        XCTAssertEqual(sharedInvalidZeroWindowTicks, TimestampUnwrap.wrapWindowTicks)
        XCTAssertEqual(sharedReorderPeriods, TimestampUnwrap.reorderPeriods)
        XCTAssertEqual(sharedMaxWindowDivisor, TimestampUnwrap.maxWindowDivisor)
    }

    /// A vector that stops being run is a vector that stops protecting
    /// anything, and a loop over whatever the array happens to hold would not
    /// notice. Updating this list is the moment to ask what changed upstream.
    func testVectorSetIsComplete() {
        let expectedIds = [
        "monotonic-24bit",
        "wrap-24bit",
        "wrap-lands-on-zero-24bit",
        "invalid-zero-signature-24bit",
        "invalid-zero-no-cascade-24bit",
        "first-sample-zero-24bit",
        "wrap-16bit",
        "zero-on-16bit-is-a-wrap",
        "backward-step-outside-window-is-a-wrap-24bit",
        "duplicate-24bit",
        "reorder-one-period-24bit",
        "reorder-one-period-16bit",
        "reorder-across-wrap-boundary-24bit",
        "wrap-after-heavy-loss-24bit",
        "wrap-after-heavy-loss-16bit",
        "wrap-spanning-dropout-1p8s-16bit",
        "wrap-spanning-dropout-152s-24bit",
        "rate-unknown-backward-step-is-a-wrap-24bit",
        "rate-unknown-zero-still-rejected-24bit",
        "zero-within-window-of-origin-24bit",
        "zero-within-window-after-wrap-24bit",
        "reorder-window-boundary-inclusive-24bit",
        "reorder-window-boundary-exclusive-24bit",
        "low-rate-clamp-16bit",
        "high-rate-reorder-24bit",
        "reorder-beyond-eight-periods-is-a-wrap-24bit"
        ]
        XCTAssertEqual(sharedUnwrapVectors.map { $0.id }, expectedIds)
        XCTAssertEqual(sharedWindowDerivationCases.count, 11)
    }

    func testAllSharedVectorsAgree() {
        for vector in sharedUnwrapVectors {
            var lastUnwrapped = 0.0
            var cycle = 0.0

            for (i, raw) in vector.raw.enumerated() {
                let result = TimestampUnwrap.unwrap(rawTicks: raw,
                                                    lastUnwrapped: lastUnwrapped,
                                                    cycle: cycle,
                                                    maxTicks: vector.modulo,
                                                    reorderWindowTicks: vector.reorderWindowTicks)
                XCTAssertEqual(result.unwrappedTicks, vector.expectedUnwrapped[i], accuracy: 0.0,
                               "\(vector.id): sample \(i)")
                XCTAssertEqual(result.rejected, vector.expectedRejected[i],
                               "\(vector.id): sample \(i) rejected")
                lastUnwrapped = result.unwrappedTicks
                cycle = result.cycle
            }

            XCTAssertEqual(cycle, Double(vector.expectedFinalCycle), accuracy: 0.0,
                           "\(vector.id): final cycle")
        }
    }

    func testWindowDerivationCases() {
        for testCase in sharedWindowDerivationCases {
            let modulo = 1 << testCase.timestampBits
            // A rate the file spells as null is a rate the host does not know.
            // Swift has no such Double, so it arrives here as a NaN - which is
            // exactly the shape an unknown rate takes in a real host.
            let rate = testCase.samplingRateHz ?? Double.nan
            let got = TimestampUnwrap.reorderWindowTicks(samplingRateHz: rate, maxTicks: modulo)
            XCTAssertEqual(got, testCase.expectedReorderWindowTicks,
                           accuracy: max(testCase.tolerance, 1e-9),
                           "window for rate \(String(describing: testCase.samplingRateHz)) "
                           + "at \(testCase.timestampBits) bits")
        }
    }

    /// The values the shared set cannot spell.
    ///
    /// An unknown rate arriving as a division result rather than as a literal
    /// zero is the case that matters: 32768 / 0 is +Infinity in Swift, not an
    /// error, and a host that lets it through gets a window wider than the
    /// modulo. Every backward step then reads as a reorder, every roll-over is
    /// lost, and nothing looks wrong until a recording comes out 512 s short.
    func testWindowIsZeroForEveryShapeOfUnknownRate() {
        let mod = TimestampUnwrap.ticksMax3Byte
        XCTAssertEqual(TimestampUnwrap.reorderWindowTicks(samplingRateHz: .infinity, maxTicks: mod), 0.0)
        XCTAssertEqual(TimestampUnwrap.reorderWindowTicks(samplingRateHz: .nan, maxTicks: mod), 0.0)
        XCTAssertEqual(TimestampUnwrap.reorderWindowTicks(samplingRateHz: 0.0, maxTicks: mod), 0.0)
        XCTAssertEqual(TimestampUnwrap.reorderWindowTicks(samplingRateHz: -5.0, maxTicks: mod), 0.0)
        // The shape it actually arrives in: interpretInquiryResponseShimmer3
        // divides 32768 by the ADC value out of the packet.
        XCTAssertEqual(TimestampUnwrap.reorderWindowTicks(samplingRateHz: 32768.0 / 0.0, maxTicks: mod), 0.0)
    }

    // MARK: - TimeSensor, which is what actually runs the rule

    /// 51.2 Hz is a divider of 640 ticks, so eight sample periods is 5120.
    private let windowAt51Point2Hz = TimestampUnwrap.reorderWindowTicks(
        samplingRateHz: 51.2, maxTicks: TimestampUnwrap.ticksMax3Byte)

    private func milliseconds(_ ticks: Double) -> Double {
        return ticks / 32768.0 * 1000.0
    }

    func testTimeSensorPlacesASwappedPairWhereItWasTaken() {
        XCTAssertEqual(windowAt51Point2Hz, 5120.0)

        let sensor = TimeSensor()
        sensor.reorderWindowTicks = windowAt51Point2Hz

        // Two adjacent packets delivered the wrong way round. Each is placed
        // when it was taken, so the series dips - honestly - rather than
        // gaining a whole modulo.
        let wire = [10000.0, 11280.0, 10640.0, 11920.0]
        let got = wire.map { sensor.calibrateTimeStamp(timeStamp: $0) }
        for (i, ticks) in wire.enumerated() {
            XCTAssertEqual(got[i], milliseconds(ticks), accuracy: 1e-9, "sample \(i)")
        }
        XCTAssertEqual(sensor.CurrentTimeStampCycle, 0.0)
        XCTAssertFalse(sensor.lastRecordRejected)
    }

    /// What the reorder window buys, stated as the difference it makes.
    ///
    /// With the branch off - which is what an unknown sampling rate has to mean
    /// - the same swapped pair is read as a roll-over and the recording gains
    /// 512 seconds from that point on. This is the old behaviour, kept as a
    /// test so that the value of wiring the rate through is not theoretical.
    func testTimeSensorWithoutAWindowChargesAModuloForTheSameSwap() {
        let sensor = TimeSensor()
        sensor.reorderWindowTicks = 0.0

        _ = sensor.calibrateTimeStamp(timeStamp: 10000)
        _ = sensor.calibrateTimeStamp(timeStamp: 11280)
        let late = sensor.calibrateTimeStamp(timeStamp: 10640)

        XCTAssertEqual(late, milliseconds(10640 + Double(TimestampUnwrap.ticksMax3Byte)),
                       accuracy: 1e-9)
        XCTAssertEqual(sensor.CurrentTimeStampCycle, 1.0)
    }

    func testTimeSensorRejectsAnUnstampedRecordWithoutDisturbingTheNext() {
        let sensor = TimeSensor()
        sensor.reorderWindowTicks = windowAt51Point2Hz

        let first = sensor.calibrateTimeStamp(timeStamp: 7406506)
        XCTAssertFalse(sensor.lastRecordRejected)

        // A record the firmware never stamped. The timeline holds where it was.
        let unstamped = sensor.calibrateTimeStamp(timeStamp: 0)
        XCTAssertTrue(sensor.lastRecordRejected)
        XCTAssertEqual(unstamped, first, accuracy: 0.0)

        // And the next real sample reads as the ordinary step forward it is,
        // not as a second roll-over.
        let next = sensor.calibrateTimeStamp(timeStamp: 7406571)
        XCTAssertFalse(sensor.lastRecordRejected)
        XCTAssertEqual(next, milliseconds(7406571), accuracy: 1e-9)
        XCTAssertEqual(sensor.CurrentTimeStampCycle, 0.0)
    }

    /// A roll-over that lands exactly on zero is still a roll-over: what
    /// separates it from an unstamped record is where its predecessor was.
    func testTimeSensorStillAcceptsAGenuineRollOverOntoZero() {
        let sensor = TimeSensor()
        sensor.reorderWindowTicks = windowAt51Point2Hz

        _ = sensor.calibrateTimeStamp(timeStamp: 16777116)
        let wrapped = sensor.calibrateTimeStamp(timeStamp: 0)

        XCTAssertFalse(sensor.lastRecordRejected)
        XCTAssertEqual(wrapped, milliseconds(Double(TimestampUnwrap.ticksMax3Byte)), accuracy: 1e-9)
        XCTAssertEqual(sensor.CurrentTimeStampCycle, 1.0)
    }

    /// Forward motion is the default, so a roll-over preceded by a long dropout
    /// is still a roll-over. A rule that defaults to "corrupt" fails here.
    func testTimeSensorKeepsARollOverAfterHeavyLoss() {
        let sensor = TimeSensor()
        sensor.reorderWindowTicks = windowAt51Point2Hz

        _ = sensor.calibrateTimeStamp(timeStamp: 16000000)
        let after = sensor.calibrateTimeStamp(timeStamp: 100)

        XCTAssertEqual(after, milliseconds(Double(TimestampUnwrap.ticksMax3Byte) + 100),
                       accuracy: 1e-9)
        XCTAssertEqual(sensor.CurrentTimeStampCycle, 1.0)
    }

    /// The ObjectCluster a consumer actually reads: the sensor values survive,
    /// the time does not, and `timestampValid` is how a caller tells.
    func testUnstampedRecordIsFlaggedOnTheObjectCluster() {
        let sensor = TimeSensor()
        sensor.packetIndexTimeStamp = 0
        sensor.sensorEnabled = true
        sensor.reorderWindowTicks = windowAt51Point2Hz

        let good = sensor.processData(sensorPacket: [0xEA, 0x03, 0x71],
                                      objectCluster: ObjectCluster(deviceName: "test"))
        XCTAssertTrue(good.timestampValid)

        let unstamped = sensor.processData(sensorPacket: [0x00, 0x00, 0x00],
                                           objectCluster: ObjectCluster(deviceName: "test"))
        XCTAssertFalse(unstamped.timestampValid)
        // The raw field is still reported as the packet sent it.
        let rawIndex = unstamped.SignalNames.firstIndex {
            $0.contains(Sensor.SensorFormats.Raw.rawValue)
        }
        XCTAssertNotNil(rawIndex)
        XCTAssertEqual(unstamped.SignalData[rawIndex!], 0.0)
    }
}
